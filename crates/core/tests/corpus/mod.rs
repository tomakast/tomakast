fn item(n: usize, title: &str) -> Item {
    Item {
        id: ItemId::new("apps", &format!("app-{n}")),
        title: title.to_string(),
        subtitle: None,
        keywords: Vec::new(),
        icon: None,
        kind: ItemKind::Application,
        source: None,
        actions: vec![Action {
            id: "launch".into(),
            title: "Launch".into(),
            shortcut: None,
        }],
    }
}

/// Every corpus item, provider `apps`. Panics on a title repeated case-insensitively.
pub fn corpus() -> Vec<Item> {
    let titles: Vec<&str> = ADDED
        .iter()
        .chain(ENGLISH)
        .chain(RUSSIAN)
        .copied()
        .collect();
    let mut seen = std::collections::HashSet::new();
    for t in &titles {
        assert!(
            seen.insert(t.to_lowercase()),
            "duplicate corpus title {t:?}"
        );
    }
    titles.iter().enumerate().map(|(n, t)| item(n, t)).collect()
}
