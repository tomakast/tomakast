"""Builds crates/places/src/cities.tsv, the built-in list of cities, from
GeoNames' cities15000.txt (https://download.geonames.org/export/dump/cities15000.zip,
CC BY 4.0, https://www.geonames.org).

    python3 -I crates/places/tools/cities.py <path to cities15000.txt> > crates/places/src/cities.tsv

Kept: places of at least MIN_POPULATION people. Names kept for each: the GeoNames name, its
ASCII form, and the alternate names written in Latin letters that start with a capital (the
lowercase ones are machine romanizations of other scripts) or in Cyrillic; at least three
letters, not all capitals (codes such as SHA), without digits and at most 40 characters;
one name per matching key. Latin alternate names only for cities of at least
MIN_POPULATION_LATIN_ALTERNATES people. Two comment lines (`#`, with the attribution), then one line per city, the most populous
first:

    latitude <TAB> longitude <TAB> country code <TAB> population <TAB> name|other|names
"""

import sys
import unicodedata

MIN_POPULATION = 100_000
# Smaller cities keep their name, its ASCII form and their Cyrillic names only.
MIN_POPULATION_LATIN_ALTERNATES = 1_000_000
MAX_NAME = 40


def script_ok(name: str) -> bool:
    letters = [c for c in name if c.isalpha()]
    if not letters:
        return False
    cyrillic = all("Ѐ" <= c <= "ӿ" for c in letters)
    latin = all(unicodedata.name(c, "").startswith("LATIN") for c in letters)
    if cyrillic:
        return True
    return latin and letters[0].isupper()


def cyrillic(name: str) -> bool:
    return any("\u0400" <= c <= "\u04ff" for c in name)


def keep(name: str) -> bool:
    letters = [c for c in name if c.isalpha()]
    return (
        3 <= len(letters)
        and len(name) <= MAX_NAME
        # All capitals: an airport or other code (SHA, CKG).
        and not all(c.isupper() for c in letters)
        and not any(c.isdigit() for c in name)
        and not any(c in name for c in "=|\t()")
        and script_ok(name)
    )


def key(name: str) -> str:
    """What a query is matched on (see `cities.rs`): lowercase, `ё` as `е`, hyphens
    as spaces, one space between words."""
    return " ".join(name.lower().replace("ё", "е").replace("-", " ").split())


def main(path: str) -> None:
    rows = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            cols = line.rstrip("\n").split("\t")
            population = int(cols[14] or 0)
            if population < MIN_POPULATION:
                continue
            names, seen = [], set()
            alternates = [n for n in cols[3].split(",") if population >= MIN_POPULATION_LATIN_ALTERNATES or cyrillic(n)]
            for name in [cols[1], cols[2], *alternates]:
                name = name.strip()
                if keep(name) and key(name) not in seen:
                    seen.add(key(name))
                    names.append(name)
            if not names:
                continue
            rows.append((population, cols[4], cols[5], cols[8], names))
    rows.sort(key=lambda r: -r[0])
    print("# Cities of GeoNames (https://www.geonames.org), CC BY 4.0, from cities15000.txt.")
    print("# Generated by crates/places/tools/cities.py; do not edit by hand.")
    for population, lat, lon, country, names in rows:
        print(f"{lat}\t{lon}\t{country}\t{population}\t{'|'.join(names)}")


if __name__ == "__main__":
    main(sys.argv[1])
