"""Builds crates/places/src/zones.tsv: where each time zone of the tz database is, from its
zone.tab and zone1970.tab (public domain), with the zones' old and other names from the
links of tzdata.zi.

    python3 -I crates/places/tools/zones.py /usr/share/zoneinfo > crates/places/src/zones.tsv

A zone's place is its line in zone.tab (one zone per country, so `Europe/Oslo` is Oslo even
where it is a link to `Europe/Berlin`), else in zone1970.tab. A link without a place of its
own takes its target's. Zones without a place (`UTC`, `Etc/GMT+3`) are left out. Two comment
lines (`#`), then one line per name, sorted:

    zone <TAB> latitude <TAB> longitude
"""

import os
import sys


def degrees(text: str, whole: int) -> float:
    """`+DDMM`, `+DDMMSS` (or DDD for longitude) as degrees."""
    sign = -1 if text[0] == "-" else 1
    digits = text[1:]
    d = int(digits[:whole])
    m = int(digits[whole : whole + 2])
    s = int(digits[whole + 2 : whole + 4] or 0)
    return sign * (d + m / 60 + s / 3600)


def coordinates(text: str) -> tuple[float, float]:
    split = max(text.rfind("+"), text.rfind("-"))
    lat, lon = text[:split], text[split:]
    return degrees(lat, 2), degrees(lon, 3)


def table(path: str) -> dict[str, tuple[float, float]]:
    places = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            cols = line.rstrip("\n").split("\t")
            places.setdefault(cols[2], coordinates(cols[1]))
    return places


def main() -> None:
    root = sys.argv[1]
    places = table(os.path.join(root, "zone.tab"))
    for zone, at in table(os.path.join(root, "zone1970.tab")).items():
        places.setdefault(zone, at)
    links = {}
    with open(os.path.join(root, "tzdata.zi"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("L "):
                _, target, name = line.split()
                links[name] = target
    for name, target in links.items():
        seen = set()
        while target not in places and target in links and target not in seen:
            seen.add(target)
            target = links[target]
        if name not in places and target in places:
            places[name] = places[target]
    print("# Time zones of the tz database (public domain): where each zone's main place is.")
    print("# Generated by crates/places/tools/zones.py; do not edit by hand.")
    for zone in sorted(places):
        lat, lon = places[zone]
        print(f"{zone}\t{lat:.4f}\t{lon:.4f}")


main()
